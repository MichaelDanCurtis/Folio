"""Independent DOCX paragraph input and reader checks; does not run Word."""
from pathlib import Path
from tempfile import gettempdir
from zipfile import ZipFile, ZIP_DEFLATED
import argparse
from docx import Document
from docx.shared import Pt
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.text import WD_LINE_SPACING
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from lxml import etree

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'test/fixtures/word-paragraphs.docx'

def fixture():
    doc = Document()
    normal = doc.styles['Normal'].paragraph_format
    normal.space_after = Pt(6)
    base = doc.styles.add_style('ParagraphBase', WD_STYLE_TYPE.PARAGRAPH)
    base.base_style = doc.styles['Normal']
    base.paragraph_format.left_indent = Pt(18)
    base.paragraph_format.line_spacing = 1.5
    derived = doc.styles.add_style('ParagraphDerived', WD_STYLE_TYPE.PARAGRAPH)
    derived.base_style = base
    derived.paragraph_format.right_indent = Pt(9)
    derived.paragraph_format.space_before = Pt(3)
    p = doc.add_paragraph(style=derived)
    p.add_run('First\t').bold = True
    p.add_run('paragraph').italic = True
    f = p.paragraph_format
    f.left_indent = Pt(36); f.space_after = Pt(12); f.keep_with_next = True
    f.tab_stops.add_tab_stop(Pt(72))
    p._p.get_or_add_pPr().find(qn('w:ind')).set('{urn:folio:paragraph-test}keep', 'indent')
    p._p.get_or_add_pPr().find(qn('w:spacing')).set('{urn:folio:paragraph-test}keep', 'spacing')
    doc.add_paragraph('Inherited paragraph', style=derived)
    p = doc.add_paragraph('Hanging paragraph', style=base)
    p.paragraph_format.first_line_indent = Pt(-12)
    p.paragraph_format.line_spacing = Pt(20)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.AT_LEAST
    t = doc.add_table(rows=1, cols=1)
    p = t.cell(0,0).paragraphs[0]; p.style = derived
    p.add_run('Cell paragraph'); p.paragraph_format.space_before=Pt(8)
    doc.sections[0].header.paragraphs[0].text='Retained header'
    SOURCE.parent.mkdir(parents=True, exist_ok=True)
    doc.save(SOURCE)
    # Exercise alternate document prefix; styles remain generated by python-docx.
    with ZipFile(SOURCE) as package:
        entries={n:package.read(n) for n in package.namelist()}
    xml=entries['word/document.xml'].decode().replace('xmlns:w=', 'xmlns:wx=').replace('<w:', '<wx:').replace('</w:', '</wx:').replace(' w:', ' wx:')
    entries['word/document.xml']=xml.encode()
    with ZipFile(SOURCE, 'w', ZIP_DEFLATED) as package:
        for name, data in entries.items(): package.writestr(name,data)
    Document(SOURCE)
    print('Created independent paragraph fixture:', SOURCE)

def check():
    folder=Path(gettempdir())/'folio-paragraph-tests'
    assert (folder/'original.docx').read_bytes()==SOURCE.read_bytes()
    assert (folder/'undone.docx').read_bytes()==SOURCE.read_bytes()
    assert (folder/'reimported.docx').read_bytes()==(folder/'edited.docx').read_bytes()
    for name in ['edited','reopened','reimported']:
        path=folder/f'{name}.docx'; doc=Document(path); p=doc.paragraphs[0]
        assert p.text=='First\tparagraph' and p.runs[0].bold and p.runs[-1].italic
        f=p.paragraph_format
        assert f.left_indent.pt==54 and f.right_indent.pt==18
        assert f.space_before.pt==9 and f.space_after.pt==15
        assert f.line_spacing.pt==24 and f.line_spacing_rule==WD_LINE_SPACING.EXACTLY
        assert f.keep_with_next and f.tab_stops[0].position.pt==72
        assert p.style.style_id=='ParagraphDerived'
        assert doc.paragraphs[1].paragraph_format.left_indent is None
        assert doc.styles['ParagraphBase'].paragraph_format.left_indent.pt==18
        assert doc.paragraphs[2].paragraph_format.first_line_indent.pt==-12
        assert doc.tables[0].cell(0,0).paragraphs[0].paragraph_format.space_before.pt==8
        with ZipFile(path) as z, ZipFile(SOURCE) as old:
            for part in old.namelist():
                if part!='word/document.xml': assert z.read(part)==old.read(part),part
            root=etree.fromstring(z.read('word/document.xml'))
            ns={'w':'http://schemas.openxmlformats.org/wordprocessingml/2006/main'}
            for tag in ['ind','spacing']:
                n=root.find(f'w:body/w:p/w:pPr/w:{tag}',ns)
                assert n.get('{urn:folio:paragraph-test}keep')==('indent' if tag=='ind' else 'spacing')
            for part in z.namelist():
                if part.endswith(('.xml','.rels')): etree.fromstring(z.read(part))
    cleared=Document(folder/'cleared.docx').paragraphs[0].paragraph_format
    assert cleared.left_indent is None and cleared.space_after is None
    inserted=Document(folder/'inserted.docx')
    assert inserted.paragraphs[1].style.style_id=='ParagraphDerived'
    assert inserted.paragraphs[1].paragraph_format.left_indent.pt==36
    assert Document(folder/'heading.docx').paragraphs[1].style.style_id=='Heading2'
    native=Document(folder/'native.docx').paragraphs[0].paragraph_format
    assert native.left_indent.pt==36 and native.space_after.pt==9 and native.line_spacing==1.4
    ui=Document(Path(gettempdir())/'folio-paragraph-ui-tests/ui-edited.docx')
    f=ui.paragraphs[0].paragraph_format
    assert f.left_indent.pt==54 and f.space_after.pt==15 and f.line_spacing.pt==24
    assert f.line_spacing_rule==WD_LINE_SPACING.EXACTLY
    assert ui.tables[0].cell(0,0).paragraphs[0].paragraph_format.space_before.pt==18
    print('Verified paragraph formatting, inherited styles, rich runs, unknown XML, tables, unchanged parts, clear-direct, new native/styled paragraphs, headings, save/reopen/reimport, UI exports and byte-identical Undo in 10 DOCX outputs.')

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--fixture',action='store_true')
    args=parser.parse_args()
    fixture() if args.fixture else check()
